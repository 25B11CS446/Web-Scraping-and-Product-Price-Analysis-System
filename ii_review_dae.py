import pandas as pd
from playwright.async_api import async_playwright

async def scrape_products():

    url = "https://scrapingsandbox.com/data-table"

    all_products = []

    async with async_playwright() as p:

        browser = await p.chromium.launch(headless=True)

        page = await browser.new_page()

        await page.goto(url, wait_until="domcontentloaded")

        await page.locator("table").wait_for()

        print("Website loaded successfully!")

        # There are 20 pages
        for page_number in range(1, 21):

            print("Scraping page:", page_number)

            # Click page number
            if page_number > 1:

                button = page.get_by_role(
                    "button",
                    name=str(page_number),
                    exact=True
                )

                await button.click()

                # Wait for table to update
                await page.wait_for_timeout(500)

            # Get table rows
            rows = page.locator("table tbody tr")

            row_count = await rows.count()

            print("Rows found:", row_count)

            # Extract every row
            for i in range(row_count):

                cells = rows.nth(i).locator("td")

                cell_count = await cells.count()

                values = []

                for j in range(cell_count):

                    value = await cells.nth(j).inner_text()

                    values.append(value.strip())

                if len(values) >= 10:

                    all_products.append(values)

        await browser.close()

    return all_products


all_products = await scrape_products()

